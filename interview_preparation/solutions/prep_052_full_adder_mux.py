"""Full adder from five 2:1 muxes and constants zero/one.

Both complements are generated by muxes; no external NOT gate.
"""

NETLIST = (
    ("nB", "B", "1", "0"),
    ("P", "A", "B", "nB"),
    ("nCin", "Cin", "1", "0"),
    ("S", "P", "Cin", "nCin"),
    ("Cout", "P", "A", "Cin"),
)

ZERO_ONLY_NETLIST = (
    ("t", "B", "A", "0"),
    ("P", "A", "B", "t"),
    ("u", "Cin", "P", "0"),
    ("S", "P", "Cin", "u"),
    ("Cout", "P", "A", "Cin"),
)


def mux(s: int, d0: int, d1: int) -> int:
    return d1 if s else d0


def full_adder(A: int, B: int, Cin: int, *, zero_only: bool = False) -> tuple[int, int]:
    if any(type(value) is not int or value not in (0, 1) for value in (A, B, Cin)):
        raise ValueError("inputs must be integer bits")
    wires = {"A": A, "B": B, "Cin": Cin, "0": 0}
    if not zero_only:
        wires["1"] = 1
    for out, select, d0, d1 in ZERO_ONLY_NETLIST if zero_only else NETLIST:
        wires[out] = mux(wires[select], wires[d0], wires[d1])
    return wires["S"], wires["Cout"]


if __name__ == "__main__":
    for A in (0, 1):
        for B in (0, 1):
            for Cin in (0, 1):
                print(A, B, Cin, "->", full_adder(A, B, Cin))
